<?php

return [
    /*
    |--------------------------------------------------------------------------
    | Публичные данные бота
    |--------------------------------------------------------------------------
    | Токен живёт в config/nutgram.php (TELEGRAM_TOKEN) и в коде не появляется.
    */
    'bot_username' => env('TELEGRAM_BOT_USERNAME'),

    /*
    |--------------------------------------------------------------------------
    | Секрет webhook
    |--------------------------------------------------------------------------
    | Передаётся в setWebhook как secret_token; Telegram присылает его обратно
    | в заголовке X-Telegram-Bot-Api-Secret-Token. Запросы без него отклоняются.
    */
    'webhook_secret' => env('TELEGRAM_WEBHOOK_SECRET'),

    /*
    |--------------------------------------------------------------------------
    | Администраторы
    |--------------------------------------------------------------------------
    | chat_id через запятую. Им уходят уведомления о новых заявках.
    */
    'admin_chat_ids' => array_values(array_filter(array_map(
        'trim',
        explode(',', (string) env('TELEGRAM_ADMIN_CHAT_IDS', ''))
    ))),

    /*
    |--------------------------------------------------------------------------
    | Рассылка
    |--------------------------------------------------------------------------
    | Telegram ограничивает бота ~30 сообщениями в секунду, поэтому рассылка
    | идёт пачками с паузой между сообщениями.
    */
    'broadcast' => [
        'chunk_size' => (int) env('TELEGRAM_BROADCAST_CHUNK', 25),
        'delay_ms' => (int) env('TELEGRAM_BROADCAST_DELAY_MS', 40),
    ],

    /*
    |--------------------------------------------------------------------------
    | Mini App (Telegram Web App)
    |--------------------------------------------------------------------------
    | url — адрес страницы /app, обязательно https: Telegram не открывает
    | Mini App по http. Пока адреса нет, кнопки Mini App в боте скрыты.
    |
    | auth_ttl — сколько секунд действуют данные запуска (initData).
    | Telegram подписывает их при открытии Mini App; старые данные
    | не принимаем, чтобы перехваченную строку нельзя было переиграть.
    */
    'mini_app' => [
        'url' => env('TELEGRAM_MINI_APP_URL'),
        'auth_ttl' => (int) env('TELEGRAM_MINI_APP_AUTH_TTL', 86400),
    ],

    /*
    |--------------------------------------------------------------------------
    | Оплата (Telegram Payments)
    |--------------------------------------------------------------------------
    | provider_token выдаёт @BotFather → Payments после подключения провайдера
    | (ЮKassa и др.). Пока токена нет, кнопки оплаты в боте и админке скрыты.
    |
    | receipt — чек по 54-ФЗ через провайдера. Включать, когда в ЮKassa
    | подключена онлайн-касса: бот тогда спрашивает у клиента телефон
    | и передаёт его провайдеру вместе с позицией чека.
    */
    'payments' => [
        'provider_token' => env('TELEGRAM_PAYMENT_PROVIDER_TOKEN'),
        'currency' => env('TELEGRAM_PAYMENT_CURRENCY', 'RUB'),
        'receipt' => [
            'enabled' => (bool) env('TELEGRAM_PAYMENT_RECEIPT', false),
            // Код ставки НДС ЮKassa: 1 — без НДС, 4 — 20% и т.д.
            'vat_code' => (int) env('TELEGRAM_PAYMENT_VAT_CODE', 1),
        ],
    ],
];
